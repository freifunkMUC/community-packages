-- Limits for the number of clients an uplink node serves.
--
-- Default: up to DEFAULT_CLIENTS DHCPv4 leases. The neighbour table and
-- conntrack are large enough for that number of clients.
--
-- Event mode (uci parker.event_mode.enabled): for large events. dnsmasq
-- gives out the full pool, does not ping new addresses and has a larger DNS
-- cache. The neighbour table and conntrack are larger. All values scale
-- with the RAM. Nodes with less than 128 MB RAM cannot use the event mode.
--
-- noderoute.lua applies the values in each cycle, so a change of the event
-- mode needs no reboot.

local M = {}

M.DEFAULT_CLIENTS = 1024
M.SYSCTL_FILE = '/etc/sysctl.d/41-parker-limits.conf'

-- The dnsmasq options this module controls in the uci dnsmasq section.
M.DNSMASQ_OPTIONS = { 'dhcpleasemax', 'noping', 'cachesize' }

local MIB = 1024 -- KiB

-- MemTotal is smaller than the RAM size: the kernel keeps some memory for
-- itself. A 128 MB node shows approximately 120 MiB, a 256 MB node
-- approximately 240 MiB.
local RAM_256 = 192 * MIB
local RAM_128 = 96 * MIB

-- Select a value by the RAM class (MemTotal in KiB): 256 MB or more,
-- 128 MB, or less.
local function by_ram(mem, big, mid, small)
	if mem > RAM_256 then
		return big
	elseif mem > RAM_128 then
		return mid
	end
	return small
end

function M.enabled(value)
	return value == true or value == '1' or value == 1
end

-- Can a node with this MemTotal (KiB) use the event mode?
function M.available(mem)
	return mem > RAM_128
end

-- Is the event mode in effect? The uci setting has no effect on a node
-- with too little RAM.
function M.active(mem, setting)
	return M.enabled(setting) and M.available(mem)
end

function M.mem_total()
	local f = io.open('/proc/meminfo')
	if not f then
		return 0
	end
	local data = f:read('*a')
	f:close()
	return tonumber(data:match('MemTotal:%s*(%d+)')) or 0
end

-- The kernel sets nf_conntrack_max from the RAM at boot. The bucket count
-- keeps that value, so we never set a lower one.
function M.conntrack_default()
	local f = io.open('/proc/sys/net/netfilter/nf_conntrack_buckets')
	if not f then
		return 0
	end
	local value = tonumber(f:read('*l'))
	f:close()
	return value or 0
end

-- The neighbour table limits (gc_thresh1..3) for IPv4 and IPv6. The
-- event argument of this and the next function is M.active(). Each IPv6
-- client has 2 to 3 addresses, so DEFAULT_CLIENTS need gc_thresh3 4096.
-- The kernel default (1024) is full at approximately 400 clients.
function M.neigh(mem, event)
	if event then
		return by_ram(mem, { 2048, 8192, 16384 }, { 1024, 4096, 8192 }, { 1024, 2048, 4096 })
	end
	return { 1024, 2048, 4096 }
end

-- nf_conntrack_max. In the lab, a festival traffic mix used approximately
-- 10 entries for each client (36101 entries for 3600 clients). Nil: keep
-- the kernel value.
function M.conntrack(mem, event, default)
	local value
	if event then
		value = by_ram(mem, 65536, 32768, nil)
	else
		value = by_ram(mem, 16384, 16384, nil)
	end
	if value == nil or value <= (default or 0) then
		return nil
	end
	return value
end

function M.sysctl_text(mem, setting, conntrack_default)
	local event = M.active(mem, setting)
	local lines = { '# Generated by parker/limits.lua. Do not edit.' }
	for _, family in ipairs({ 'ipv4', 'ipv6' }) do
		for i, value in ipairs(M.neigh(mem, event)) do
			table.insert(lines, string.format('net.%s.neigh.default.gc_thresh%d=%d', family, i, value))
		end
	end
	local ct = M.conntrack(mem, event, conntrack_default)
	if ct ~= nil then
		table.insert(lines, string.format('net.netfilter.nf_conntrack_max=%d', ct))
	end
	return table.concat(lines, '\n') .. '\n'
end

-- Write the sysctl file and apply it if it has changed. Returns whether it
-- has changed.
function M.apply_sysctl(setting, path)
	path = path or M.SYSCTL_FILE
	local text = M.sysctl_text(M.mem_total(), setting, M.conntrack_default())
	local f = io.open(path)
	if f then
		local old = f:read('*a')
		f:close()
		if old == text then
			return false
		end
	end
	f = assert(io.open(path, 'w'))
	f:write(text)
	f:close()
	os.execute('sysctl -e -p ' .. path .. ' >/dev/null 2>&1')
	return true
end

-- The dnsmasq options for an uplink node with a DHCPv4 pool of the given
-- size. A nil value removes the option (dnsmasq default).
function M.dnsmasq(mem, setting, pool)
	if not M.active(mem, setting) then
		return { dhcpleasemax = M.DEFAULT_CLIENTS }
	end
	return {
		dhcpleasemax = math.max(pool, M.DEFAULT_CLIENTS),
		-- dnsmasq waits up to 3 s for each ping and stops all DHCP in that
		-- time. With many new clients, the DHCP socket overflows and
		-- renewals get lost.
		noping = 1,
		cachesize = by_ram(mem, 4096, 2048, 1000),
	}
end

return M
